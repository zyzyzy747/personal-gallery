def main():
    with open(os.path.join(SHEETS, 'manifest.json'), encoding='utf-8') as f:
        manifest = json.load(f)

    out = {}
    stat = {'tagged': 0, 'skipped': 0, 'missing': 0}
    for sheet, items in ANN.items():
        grp = {it['no']: it['id'] for it in manifest.get(sheet, [])}
        for no, tags in items.items():
            sid = grp.get(int(no))
            if sid is None:
                stat['missing'] += 1
                continue
            if not tags:
                stat['skipped'] += 1
                continue
            out[str(sid)] = {'tags': tags, 'src': 'vision',
                             'at': time.strftime('%Y-%m-%dT%H:%M:%S')}
            stat['tagged'] += 1

    dst = os.path.join(ASSETS, 'auto-tags.json')
    with open(dst, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, separators=(',', ':'))
    print('已标注 %(tagged)d 个，跳过 %(skipped)d 个（画面信息不足），映射失败 %(missing)d 个' % stat)
    print('写出 %s  (%.1f KB)' % (dst, os.path.getsize(dst) / 1024))

    # 统计标签分布
    import collections
    c = collections.Counter()
    for v in out.values():
        c.update(v['tags'])
    print('\n标签分布：')
    for k, v in c.most_common():
        print('  %-8s %3d' % (k, v))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main()
